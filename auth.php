<?php

declare(strict_types=1);

if (session_status() !== PHP_SESSION_ACTIVE) {
    session_start();
}

/*
|--------------------------------------------------------------------------
| الهوية الحالية
|--------------------------------------------------------------------------
*/

function currentAnzId(): ?string
{
    $anzId = $_SESSION['anz_id'] ?? null;

    if (!$anzId) {
        return null;
    }

    return trim((string)$anzId);
}


/*
|--------------------------------------------------------------------------
| الدور
|--------------------------------------------------------------------------
*/

function currentRole(): string
{
    return strtolower(
        trim(
            (string)($_SESSION['role'] ?? 'student')
        )
    );
}


/*
|--------------------------------------------------------------------------
| هل المستخدم مسجل؟
|--------------------------------------------------------------------------
*/

function isLoggedIn(): bool
{
    return currentAnzId() !== null;
}


/*
|--------------------------------------------------------------------------
| حماية الصفحة
|--------------------------------------------------------------------------
*/

function requireLogin(): void
{
    if (!isLoggedIn()) {

        http_response_code(401);

        exit('يجب تسجيل الدخول أولاً.');

    }
}


/*
|--------------------------------------------------------------------------
| منع الوصول حسب الدور
|--------------------------------------------------------------------------
*/

function requireRole(array $roles): void
{
    requireLogin();

    $role = currentRole();

    if (!in_array($role, $roles, true)) {

        http_response_code(403);

        exit('ليس لديك صلاحية للوصول إلى هذه الصفحة.');

    }
}